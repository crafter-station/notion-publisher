import assert from 'node:assert/strict';
import ts from 'typescript';
import {readFile} from 'node:fs/promises';
const files=['channel-settings','postiz-versions','notion-content','notion-write-plan'];
const source=(await Promise.all(files.map(name=>readFile(new URL('../lib/'+name+'.ts',import.meta.url),'utf8')))).join('\n').replace(/^import .*?;$/gm,'');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {notionContent,notionWritePlan:plan,postizFields}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const rich=value=>({type:'rich_text',rich_text:value?[{plain_text:value}]:[]});
const props={Name:{type:'title',title:[{plain_text:'Title'}]},Caption:rich('Body'),'X Post':rich('First'),'Twitter Post':rich('Threads'),'Typefully Thread':rich('Second'), ...Object.fromEntries(Object.values(postizFields).map(name=>[name,rich(name)])),Status:{type:'status',status:{name:'Draft'}}};
const before=notionContent(props);
assert.deepEqual(plan(props,before).fields,[]);
const desired=structuredClone(before);desired.title='Edited';desired.versions.X='New first\n\n\n\nNew second';desired.versions.postiz_X='Provider copy';
const patch=plan(props,desired);
assert.deepEqual(patch.fields.sort(),['Name','Postiz X','Typefully Thread','X Post'].sort());
assert.equal(patch.properties['Typefully Thread'].rich_text[0].text.content,'New second');
assert.equal(patch.properties.Status,undefined);
assert.deepEqual(notionContent(props),before);
const collision=structuredClone(props);delete collision['X Post'];
const cross=notionContent(collision);cross.versions.Threads='Different';
assert.throws(()=>plan(collision,cross),/no representa/);
const empty=structuredClone(before);empty.versions.postiz_X='';assert.throws(()=>plan(props,empty),/no representa/);
delete empty.versions.postiz_X;assert.deepEqual(plan(props,empty).properties['Postiz X'],{rich_text:[]});
const unknown=structuredClone(before);unknown.versions.Moltbook='Copy';assert.throws(()=>plan(props,unknown),/no tiene un campo/);
const long=structuredClone(before);long.body='a'.repeat(1999)+'😀'+'b'.repeat(2000);
const chunks=plan(props,long).properties.Caption.rich_text;
assert(chunks.every(t=>t.text.content.length<=2000));assert.equal(chunks.map(t=>t.text.content).join(''),long.body);
long.body='x'.repeat(200001);assert.throws(()=>plan(props,long),/límite/);
console.log('Notion write preflight passed: minimal patch, independent provider text, threads, alias collisions, empty/deleted variants, unsupported channels, Unicode and size limits. No network writes.');
